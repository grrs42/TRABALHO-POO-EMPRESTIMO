
-- Sistema de Gerenciamento de Empréstimos Acadêmicos
-- Estrutura inicial do banco PostgreSQL.
-- Executar somente em um banco novo e vazio.

BEGIN;

-- Usuários cadastrados no sistema.
CREATE TABLE public.usuarios (
    matricula VARCHAR(30) PRIMARY KEY,
    nome VARCHAR(150) NOT NULL
);

-- Organizações responsáveis pelos materiais.
CREATE TABLE public.grupos_responsaveis (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(30) NOT NULL UNIQUE,
    nome VARCHAR(150) NOT NULL
);

-- Categorias dos materiais acadêmicos.
CREATE TABLE public.tipos_material (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sigla VARCHAR(3) NOT NULL UNIQUE,
    nome VARCHAR(150) NOT NULL,
    especializacao VARCHAR(20) NOT NULL DEFAULT 'OUTRO',

    CONSTRAINT tipos_material_especializacao_check
    CHECK (
        especializacao IN (
            'CALCULADORA',
            'JALECO',
            'LIVRO',
            'OUTRO'
        )
    )
);

-- Exemplares físicos dos materiais acadêmicos.
CREATE TABLE public.materiais (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(30) NOT NULL UNIQUE,
    numero INTEGER NOT NULL,

    tipo_id INTEGER NOT NULL,
    grupo_id INTEGER NOT NULL,

    disponivel BOOLEAN NOT NULL DEFAULT TRUE,

    -- Atributo comum opcional.
    marca VARCHAR(100),

    -- Atributos das subclasses.
    modelo VARCHAR(100),
    tamanho VARCHAR(10),
    titulo VARCHAR(200),
    editora VARCHAR(120),
    descricao TEXT,

    CONSTRAINT materiais_tipo_fk
        FOREIGN KEY (tipo_id)
        REFERENCES public.tipos_material(id),

    CONSTRAINT materiais_grupo_fk
        FOREIGN KEY (grupo_id)
        REFERENCES public.grupos_responsaveis(id),

    CONSTRAINT materiais_tipo_numero_unique
        UNIQUE (tipo_id, numero),

    CONSTRAINT materiais_numero_positivo_check
        CHECK (numero > 0)
);

COMMIT;