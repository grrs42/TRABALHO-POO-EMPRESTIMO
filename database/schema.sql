BEGIN;

CREATE TABLE public.usuarios (
    matricula VARCHAR(30) PRIMARY KEY,
    nome VARCHAR(150) NOT NULL
);

CREATE TABLE public.grupos_responsaveis (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(30) NOT NULL UNIQUE,
    nome VARCHAR(150) NOT NULL
);

CREATE TABLE public.tipos_material (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sigla VARCHAR(3) NOT NULL UNIQUE,
    nome VARCHAR(150) NOT NULL,
    especializacao VARCHAR(20) NOT NULL DEFAULT 'OUTRO',

    CONSTRAINT tipos_material_especializacao_check
    CHECK (
        especializacao IN (
            'CALCULADORA',
            'JALECO',
            'LIVRO',
            'OUTRO'
        )
    )
);

CREATE TABLE public.materiais (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(30) NOT NULL UNIQUE,
    numero INTEGER NOT NULL,

    tipo_id INTEGER NOT NULL,
    grupo_id INTEGER NOT NULL,

    disponivel BOOLEAN NOT NULL DEFAULT TRUE,

    marca VARCHAR(100),

    modelo VARCHAR(100),
    tamanho VARCHAR(10),
    titulo VARCHAR(200),
    editora VARCHAR(120),
    descricao TEXT,

    CONSTRAINT materiais_tipo_fk
        FOREIGN KEY (tipo_id)
        REFERENCES public.tipos_material(id),

    CONSTRAINT materiais_grupo_fk
        FOREIGN KEY (grupo_id)
        REFERENCES public.grupos_responsaveis(id),

    CONSTRAINT materiais_tipo_numero_unique
        UNIQUE (tipo_id, numero),

    CONSTRAINT materiais_numero_positivo_check
        CHECK (numero > 0)
);

CREATE TABLE public.emprestimos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_matricula VARCHAR(30) NOT NULL
        REFERENCES public.usuarios(matricula),
    material_id INTEGER NOT NULL
        REFERENCES public.materiais(id),
    status VARCHAR(12) NOT NULL
        CHECK (status IN ('PENDENTE', 'ATIVO', 'RECUSADO', 'DEVOLVIDO')),
    data_solicitacao TIMESTAMP NOT NULL,
    data_confirmacao TIMESTAMP,
    data_prevista_devolucao DATE,
    data_devolucao TIMESTAMP,
    responsavel_confirmacao VARCHAR(30)
        REFERENCES public.grupos_responsaveis(codigo)
);

CREATE UNIQUE INDEX emprestimo_aberto_material_unique
    ON public.emprestimos (material_id)
    WHERE status IN ('PENDENTE', 'ATIVO');

CREATE TABLE public.contas_acesso (
    login VARCHAR(30) PRIMARY KEY,
    senha_hash VARCHAR(128) NOT NULL,
    salt VARCHAR(64) NOT NULL,
    tipo VARCHAR(10) NOT NULL
        CHECK (tipo IN ('ESTUDANTE', 'GRUPO')),
    usuario_matricula VARCHAR(30) UNIQUE
        REFERENCES public.usuarios(matricula),
    grupo_codigo VARCHAR(30) UNIQUE
        REFERENCES public.grupos_responsaveis(codigo),

    CONSTRAINT contas_acesso_vinculo_check CHECK (
        (tipo = 'ESTUDANTE' AND usuario_matricula IS NOT NULL AND grupo_codigo IS NULL)
        OR
        (tipo = 'GRUPO' AND grupo_codigo IS NOT NULL AND usuario_matricula IS NULL)
    )
);

COMMIT;
